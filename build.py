# -*- coding: utf-8 -*-
"""
nine-balance-widget build script
============================================================================
src/providers.js + src/pricing.js + src/balance.js + src/widget.js
(module sources concatenated verbatim — multiple ESM exports are fine)
+ src/shell.js (relative imports stripped) -> single-file plugin.js.
The nine mascots (assets/transparent/*.webp, tightly cropped to their alpha
bbox) are injected into the MASCOTS table as base64 data URIs.

Every surgical splice asserts an exact hit; node --check gates the build —
the artifact is never written on failure.
Usage: python build.py
"""
import base64
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
OUT = os.path.join(HERE, 'plugin.js')


def fail(msg):
    print('BUILD FAILED: ' + msg, file=sys.stderr)
    sys.exit(1)


def read(name):
    with open(os.path.join(SRC, name), encoding='utf-8') as f:
        return f.read()


def sub(text, old, new, count, label):
    n = text.count(old)
    if n != count:
        fail('%s: expected %d, found %d  needle=%r' % (label, count, n, old[:100]))
    return text.replace(old, new)


# ── 1. module sources ─────────────────────────────────────────────────────────────
providers = read('providers.js')
pricing = read('pricing.js')
balance = read('balance.js')
widget = read('widget.js')
shell = read('shell.js')

# 2. strip relative imports (functions live in the same concatenated module)
shell = sub(shell,
            "import { PROVIDERS, PROVIDER_ORDER, sourceTier, srcKey } from './providers.js'\n",
            '', 1, 'shell-import-providers')
shell = sub(shell,
            "import { mountWidget, unmountWidget } from './widget.js'\n",
            '', 1, 'shell-import-widget')
shell = sub(shell,
            "import { fetchSource } from './balance.js'\n",
            '', 1, 'shell-import-balance')
shell = sub(shell,
            "import { DEFAULT_PRICES, SCHEDULES, effectivePrices, estimateCost, dayEstimate, scheduleState, priceKey, tokenKey, fmtTokens } from './pricing.js'\n",
            '', 1, 'shell-import-pricing')

# 3. none of the three source files may keep a relative import
for name, text in (('shell', shell), ('providers', providers), ('pricing', pricing),
                   ('balance', balance), ('widget', widget)):
    for line in text.split('\n'):
        if "from './" in line:
            fail('%s: relative import not stripped: %r' % (name, line.strip()))

# 3b. nine mascots -> base64 data URI table (MASCOTS placeholder)
COMPACT = os.path.join(HERE, 'assets', 'transparent')
ids = ['deepseek', 'minimax', 'glm', 'kimi', 'mimo', 'chatgpt', 'claude', 'gemini', 'grok']
entries = []
total = 0
for pid in ids:
    p = os.path.join(COMPACT, pid + '.webp')
    if not os.path.exists(p):
        fail('missing compact mascot: ' + p)
    raw = open(p, 'rb').read()
    total += len(raw)
    entries.append('%s: %r' % (pid, 'data:image/webp;base64,' + base64.b64encode(raw).decode('ascii')))
mascots = 'export const MASCOTS = {\n  ' + ',\n  '.join(entries) + '\n}'
if widget.count('/*@MASCOTS@*/') != 1:
    fail('MASCOTS placeholder count != 1')
widget = widget.replace('/*@MASCOTS@*/', mascots)

# ── 2. assemble ───────────────────────────────────────────────────────────────
banner = '''/**
 * nine-balance-widget — multi-provider balance widget for the Hermes desktop app
 * (single-file build artifact). Generated by build.py from src/ — do not edit.
 * See src/ and README for structure and provenance.
 */
'''

plugin = banner + providers + '\n\n' + pricing + '\n\n' + balance + '\n\n' + widget + '\n\n' + shell

# ── 3. residue scan (local paths / secret patterns) ──────────────────────────────────────
forbidden = ['C:\\\\Users', 'C:/Users', 'sk-', 'ghp_', 'api_key=', 'API_KEY=*** ...']
for tok in forbidden:
    if tok in plugin:
        fail('forbidden token in product: %r' % tok)

# ── 4. syntax gate: copy to .mjs and run node --check ──────────────────────────────────
tmp = os.path.join(HERE, '__check.mjs')
with open(tmp, 'w', encoding='utf-8', newline='\n') as f:
    f.write(plugin)
try:
    r = subprocess.run(['node', '--check', tmp], capture_output=True, text=True, encoding='utf-8')
    if r.returncode != 0:
        fail('node --check:\n' + (r.stderr or r.stdout))
finally:
    if os.path.exists(tmp):
        os.remove(tmp)

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(plugin)

# Catalog entrypoint (plugin-catalog desktop form): byte-identical to the root artifact.
DENTRY = os.path.join(HERE, 'desktop', 'plugin.js')
os.makedirs(os.path.dirname(DENTRY), exist_ok=True)
with open(DENTRY, 'w', encoding='utf-8', newline='\n') as f:
    f.write(plugin)

print('OK -> %s (%.1f KB)' % (OUT, os.path.getsize(OUT) / 1024))
print('OK -> %s (%.1f KB)' % (DENTRY, os.path.getsize(DENTRY) / 1024))
print('  providers: 9, mascots: %d (%d KB raw), shell lines: %d'
      % (len(ids), total // 1024, shell.count('\n')))
